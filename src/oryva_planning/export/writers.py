"""Deterministic writers for CSV, JSON, SQL seed, SQLite, and SHA-256 checksums."""

from __future__ import annotations

import hashlib
import json
import sqlite3
from pathlib import Path
from typing import Any

import pandas as pd

from oryva_planning.config import PlanningConfig
from oryva_planning.schema.ground_truth import GROUND_TRUTH_COLUMNS
from oryva_planning.schema.registry import ENTITY_ORDER, ENTITY_REGISTRY, generate_full_sql_ddl


def compute_sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _canonicalize_table(table_name: str, df: pd.DataFrame) -> pd.DataFrame:
    spec = ENTITY_REGISTRY[table_name]
    return df[spec.column_names()].sort_values(spec.primary_key, kind="mergesort").reset_index(drop=True)


def _sql_literal(value: Any) -> str:
    if value is None or (not isinstance(value, (str, bool)) and pd.isna(value)):
        return "NULL"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        return f"{value:.4f}"
    escaped = str(value).replace("'", "''")
    return f"'{escaped}'"


def _write_json_stream(df: pd.DataFrame, path: Path) -> None:
    cols = list(df.columns)
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write("[\n")
        total = len(df)
        for idx, row_vals in enumerate(df.itertuples(index=False, name=None)):
            rec: dict[str, Any] = {}
            for col, val in zip(cols, row_vals):
                if val is None or (not isinstance(val, (str, bool)) and pd.isna(val)):
                    rec[col] = None
                elif isinstance(val, float):
                    rec[col] = round(val, 4)
                else:
                    rec[col] = val
            sep = "," if idx < total - 1 else ""
            fh.write("  " + json.dumps(rec, ensure_ascii=False) + sep + "\n")
        fh.write("]\n")


def export_all(
    config: PlanningConfig,
    tables: dict[str, pd.DataFrame],
    ground_truth_df: pd.DataFrame,
    detector_metrics: dict[str, dict[str, float | int]] | None = None,
    output_dir: Path | None = None,
) -> dict[str, Any]:
    base = Path(output_dir) if output_dir is not None else Path(config.export.output_dir)
    inputs_dir = base / "inputs"
    gt_dir = base / "ground_truth"
    csv_dir = inputs_dir / "csv"
    json_dir = inputs_dir / "json"
    sql_dir = inputs_dir / "sql"
    sqlite_dir = inputs_dir / "sqlite"

    for d in (csv_dir, json_dir, sql_dir, sqlite_dir, gt_dir):
        d.mkdir(parents=True, exist_ok=True)

    formats = set(config.export.formats)
    float_fmt = config.export.float_format
    lineterm = config.export.line_terminator

    canonical: dict[str, pd.DataFrame] = {tbl: _canonicalize_table(tbl, tables[tbl]) for tbl in ENTITY_ORDER}

    row_counts: dict[str, int] = {}
    checksums: dict[str, str] = {}

    if "csv" in formats:
        for tbl in ENTITY_ORDER:
            df = canonical[tbl]
            row_counts[tbl] = len(df)
            csv_path = csv_dir / f"{tbl}.csv"
            df.to_csv(csv_path, index=False, float_format=float_fmt, lineterminator=lineterm)
            checksums[f"inputs/csv/{tbl}.csv"] = compute_sha256(csv_path)

    if "json" in formats:
        for tbl in ENTITY_ORDER:
            _write_json_stream(canonical[tbl], json_dir / f"{tbl}.json")

    if "sql" in formats:
        (sql_dir / "schema.sql").write_text(generate_full_sql_ddl(), encoding="utf-8", newline="\n")
        seed_path = sql_dir / "seed.sql"
        with seed_path.open("w", encoding="utf-8", newline="\n") as fh:
            fh.write("-- Deterministic SQL seed generated by oryva-planning\n")
            fh.write(f"-- Scale: {config.name} | Seed: {config.seed}\n\n")
            fh.write("BEGIN TRANSACTION;\n\n")
            for tbl in ENTITY_ORDER:
                df = canonical[tbl]
                if df.empty:
                    continue
                col_list = ", ".join(df.columns)
                fh.write(f"-- Table: {tbl} ({len(df)} rows)\n")
                for row_vals in df.itertuples(index=False, name=None):
                    vals_sql = ", ".join(_sql_literal(v) for v in row_vals)
                    fh.write(f"INSERT INTO {tbl} ({col_list}) VALUES ({vals_sql});\n")
                fh.write("\n")
            fh.write("COMMIT;\n")

    if "sqlite" in formats:
        db_path = sqlite_dir / "oryva_planning.sqlite"
        if db_path.exists():
            db_path.unlink()
        conn = sqlite3.connect(str(db_path))
        try:
            conn.executescript(generate_full_sql_ddl())
            for tbl in ENTITY_ORDER:
                canonical[tbl].to_sql(tbl, conn, if_exists="append", index=False)
            conn.commit()
        finally:
            conn.close()

    gt_sorted = (
        ground_truth_df[list(GROUND_TRUTH_COLUMNS)]
        .sort_values("ground_truth_id", kind="mergesort")
        .reset_index(drop=True)
    )
    gt_csv = gt_dir / "ground_truth.csv"
    gt_sorted.to_csv(gt_csv, index=False, lineterminator=lineterm)
    checksums["ground_truth/ground_truth.csv"] = compute_sha256(gt_csv)
    row_counts["ground_truth"] = len(gt_sorted)

    _write_json_stream(gt_sorted, gt_dir / "ground_truth.json")

    if detector_metrics is not None:
        (gt_dir / "detector_metrics.json").write_text(
            json.dumps(detector_metrics, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
            newline="\n",
        )

    checksum_lines = [f"{checksums[k]}  {k}" for k in sorted(checksums.keys())]
    (base / "checksums.sha256").write_text("\n".join(checksum_lines) + "\n", encoding="utf-8", newline="\n")

    return {"row_counts": row_counts, "checksums": checksums, "output_dir": str(base)}
